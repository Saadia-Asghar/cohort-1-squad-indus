export function exportKhataLedgerPDF(khataAnalytics: any, ledgerEntries: any[], businessName: string) {
  const doc = new jsPDF();
  let y = 45;
  let page = 1;

  drawHeader(doc, "General Ledger Report", businessName, khataAnalytics?.label || "Statement");
  drawFooter(doc, page);

  // Profitability metrics section
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text("Profitability Audit Summary", 15, y);
  y += 8;

  doc.setFontSize(10);
  doc.text("Category", 15, y);
  doc.text("Financial Record", 120, y);
  y += 3;
  doc.line(15, y, 195, y);
  y += 6;

  doc.setFont("helvetica", "normal");
  const records = [
    { label: "Gross Sales Revenue", val: `PKR ${(khataAnalytics?.revenue ?? 0).toLocaleString()}` },
    { label: "Completed Orders Count", val: String(khataAnalytics?.deliveredOrders ?? 0) },
    { label: "Estimated Product COGS (Recipes)", val: `PKR ${(khataAnalytics?.estimatedCogsFromRecipes ?? 0).toLocaleString()}` },
    { label: "Manual Operating Expenses", val: `PKR ${(khataAnalytics?.manualExpenses ?? 0).toLocaleString()}` },
    { label: "Bakers Delivery Cost Paid", val: `PKR ${(khataAnalytics?.deliveryCosts ?? 0).toLocaleString()}` },
    { label: "Estimated Net Profit", val: `PKR ${(khataAnalytics?.netProfitAfterCogs ?? 0).toLocaleString()}` },
  ];

  records.forEach((r) => {
    doc.text(r.label, 15, y);
    doc.text(r.val, 120, y);
    y += 7;
  });

  y += 10;

  // Ledger entries table
  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.text("Expense Ledger Log", 15, y);
  y += 8;

  doc.setFontSize(10);
  doc.text("Date", 15, y);
  doc.text("Type", 40, y);
  doc.text("Category", 75, y);
  doc.text("Description", 115, y);
  doc.text("Amount", 175, y);
  y += 3;
  doc.line(15, y, 195, y);
  y += 6;

  doc.setFont("helvetica", "normal");
  ledgerEntries.forEach((e) => {
    if (y > 265) {
      doc.addPage();
      page++;
      y = 45;
      drawHeader(doc, "General Ledger Report", businessName, khataAnalytics?.label || "Statement");
      drawFooter(doc, page);

      doc.setFont("helvetica", "bold");
      doc.text("Date", 15, y);
      doc.text("Type", 40, y);
      doc.text("Category", 75, y);
      doc.text("Description", 115, y);
      doc.text("Amount", 175, y);
      y += 3;
      doc.line(15, y, 195, y);
      y += 6;
      doc.setFont("helvetica", "normal");
    }

    doc.text(e.entryDate || "N/A", 15, y);
    doc.text(e.type?.replace("_", " ") || "expense", 40, y);
    doc.text(e.category || "general", 75, y);
    
    // Truncate description if too long
    const descText = e.description ? (e.description.length > 28 ? e.description.slice(0, 26) + ".." : e.description) : "";
    doc.text(descText, 115, y);
    
    doc.text(`Rs. ${(e.amountPkr ?? 0).toLocaleString()}`, 175, y);
    y += 8;
  });

  doc.save("khata-ledger-statement.pdf");
}

export function exportOrdersPDF(orders: any[], businessName: string) {
  const doc = new jsPDF();
  let y = 45;
  let page = 1;

  drawHeader(doc, "Orders Log", businessName, `Total Active: ${orders.length}`);
  drawFooter(doc, page);

  // Table Headers
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.text("ID", 15, y);
  doc.text("Customer", 28, y);
  doc.text("Delivery Date", 70, y);
  doc.text("Status", 100, y);
  doc.text("Items Summary", 130, y);
  doc.text("Total Price", 180, y);
  
  y += 3;
  doc.line(15, y, 195, y);
  y += 6;

  doc.setFont("helvetica", "normal");
  orders.forEach((o) => {
    if (y > 265) {
      doc.addPage();
      page++;
      y = 45;
      drawHeader(doc, "Orders Log", businessName, `Total Active: ${orders.length}`);
      drawFooter(doc, page);

      doc.setFont("helvetica", "bold");
      doc.text("ID", 15, y);
      doc.text("Customer", 28, y);
      doc.text("Delivery Date", 70, y);
      doc.text("Status", 100, y);
      doc.text("Items Summary", 130, y);
      doc.text("Total Price", 180, y);
      
      y += 3;
      doc.line(15, y, 195, y);
      y += 6;
      doc.setFont("helvetica", "normal");
    }

    doc.text(String(o.id), 15, y);
    
    const customer = o.buyerName ? (o.buyerName.length > 15 ? o.buyerName.slice(0, 13) + ".." : o.buyerName) : "Guest";
    doc.text(customer, 28, y);
    doc.text(o.deliveryDate || "N/A", 70, y);
    doc.text(o.status || "new", 100, y);
    
    // Items summary
    const summary = o.items
      ?.map((item: any) => `${item.productName} x${item.quantity}`)
      .join(", ") || o.productName || "Custom Order";
    const summaryText = summary.length > 24 ? summary.slice(0, 22) + ".." : summary;
    doc.text(summaryText, 130, y);
    
    doc.text(`Rs. ${(o.totalPkr ?? 0).toLocaleString()}`, 180, y);
    y += 8;
  });

  doc.save("bakery-orders-log.pdf");
}
